def test_auto_sat_qc_two_pass_writes_expected_artifacts(tmp_path: Path, monkeypatch):
    rtkconf = tmp_path / "um980-autoqc-baseline.conf"
    rover = tmp_path / "rover.obs"
    base = tmp_path / "base.obs"
    nav = tmp_path / "gps.nav"
    for path in (rover, base, nav):
        path.write_text("input\n", encoding="ascii")
    rtkconf.write_text("pos1-elmask        =15\npos1-exclsats      =\nout-outstat        =residual\n", encoding="ascii")
    calls: list[Path] = []

    def fake_run_rnx2rtkp(**kwargs):
        output_file = kwargs["output_file"]
        calls.append(output_file)
        output_file.write_text("% header\n2026/05/23 00:00:00 0 0 0 1\n", encoding="ascii")
        Path(str(output_file) + ".stat").write_text(
            _sat_rows("G26", el=55, resp=5.5, resc=0.25, rejc=0, count=50)
            + _sat_rows("G05", el=60, resp=0.2, resc=0.01, rejc=0, count=50),
            encoding="ascii",
        )
        return argparse.Namespace(args=["rnx2rtkp", str(output_file)], output_file=output_file)

    monkeypatch.setattr(cli, "run_rnx2rtkp", fake_run_rnx2rtkp)
    args = argparse.Namespace(
        auto_sat_qc=True,
        auto_sat_qc_source="stat",
        max_auto_exclude=4,
        max_high_el_exclude=1,
        max_low_el_exclude=3,
        min_remaining_sats=1,
        min_remaining_constellations=1,
        output_format="pos",
        rtklib_path_style="unix",
        dry_run=False,
        debug=False,
        verbose=False,
    )

    command = cli._run_rtklib_with_optional_auto_qc(
        args=args,
        rnx2rtkp="rnx2rtkp",
        rtkconf=rtkconf,
        output_file=tmp_path / "run.pos",
        rover_obs=rover,
        base_obs=[base],
        nav_files=[nav],
        base_obs_arg=None,
        rtk_options=[],
        base_ecef=None,
        base_llh=None,
    )

    assert calls == [tmp_path / "run.pass1.pos", tmp_path / "run.pos"]
    assert command.output_file == tmp_path / "run.pos"
    assert (tmp_path / "run.pass1.stat").exists()
    assert (tmp_path / "run.stat").exists()
    assert "G26" in (tmp_path / "run.autoqc.derived.conf").read_text(encoding="utf-8")
    assert (tmp_path / "run.autoqc.report.md").exists()
    assert (tmp_path / "run.autoqc.report.json").exists()
